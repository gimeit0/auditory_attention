def set_east_asian_font(run):
    run.font.name = JAPANESE_FONT
    rpr = run._r.get_or_add_rPr()
    for tag in ("a:latin", "a:ea", "a:cs"):
        element = rpr.find(qn(tag))
        if element is None:
            element = OxmlElement(tag)
            rpr.append(element)
        element.set("typeface", JAPANESE_FONT)


def replace_paragraph(paragraph, text):
    if not paragraph.runs:
        run = paragraph.add_run()
    else:
        run = paragraph.runs[0]
    run.text = text
    set_east_asian_font(run)
    for extra_run in paragraph.runs[1:]:
        extra_run.text = ""
        set_east_asian_font(extra_run)


def main():
    presentation = Presentation(SOURCE)

    for slide_number, replacements in SLIDE_TEXT.items():
        slide = presentation.slides[slide_number - 1]
        for (shape_index, paragraph_index), japanese in replacements.items():
            paragraph = slide.shapes[shape_index].text_frame.paragraphs[paragraph_index]
            replace_paragraph(paragraph, japanese)

    for slide_number in range(2, 19):
        slide = presentation.slides[slide_number - 1]
        footer = slide.shapes[-1]
        if footer.has_text_frame:
            replace_paragraph(
                footer.text_frame.paragraphs[0],
                f"Griffith et al.（2026）· 単一チェックポイントによる定性的再現"
                f"                                      {slide_number}/19",
            )

    for slide, note in zip(presentation.slides, NOTES):
        slide.notes_slide.notes_text_frame.text = note
        for paragraph in slide.notes_slide.notes_text_frame.paragraphs:
            for run in paragraph.runs:
                set_east_asian_font(run)

    presentation.save(OUTPUT)
    print(OUTPUT)


if __name__ == "__main__":
    main()
